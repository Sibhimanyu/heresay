// Regenerates functions/src/core/bot-logo.ts: the Heresay mark on white, 512x512 JPEG
// (Telegram's static profile photos are JPG), embedded so core needs no files or dependencies.
// Run: node scripts/bot-logo.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';

const root = fileURLToPath(new URL('..', import.meta.url));
const svg = readFileSync(root + 'public/mark.svg', 'utf8');
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 512, height: 512 } });
await page.setContent(`<body style="margin:0;background:#fff;display:grid;place-items:center;height:512px">`
  + `<img width="360" height="360" src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}"></body>`);
await page.waitForFunction(() => document.images[0].complete);
const jpeg = await page.screenshot({ type: 'jpeg', quality: 90 });
await browser.close();
if (jpeg.length > 60_000) throw new Error('Logo too large: ' + jpeg.length);
writeFileSync(root + 'functions/src/core/bot-logo.ts',
  `// Generated by scripts/bot-logo.mjs. Do not edit.\n/** The Heresay mark on white, 512x512 JPEG, base64. */\nexport const BOT_LOGO_JPEG_BASE64 =\n  '${jpeg.toString('base64')}';\n`);
console.log('bot-logo.ts', jpeg.length, 'bytes');
